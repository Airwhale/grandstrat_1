const MAPS_BY_TERRAIN: Record<TerrainType, TileCode[][][]> = {
  urban: URBAN_MAPS,
  jungle: JUNGLE_MAPS,
  desert: DESERT_MAPS,
  arctic: ARCTIC_MAPS,
  mountain: MOUNTAIN_MAPS,
  coastal: COASTAL_MAPS,
};

const TILE_CODE_TO_TYPE: Record<TileCode, TileType> = {
  0: 'floor',
  1: 'wall',
  2: 'halfCover',
  3: 'fullCover',
  4: 'highGround',
  5: 'water',
  6: 'hazard',
  7: 'objective',
};

export function generateCombatMap(terrain: TerrainType): { type: TileType; elevation: number }[][] {
  const templates = MAPS_BY_TERRAIN[terrain];
  const template = templates[Math.floor(Math.random() * templates.length)];

  return template.map(row =>
    row.map(code => {
      // Randomize some floor tiles into cover occasionally
      let finalCode = code;
      if (code === 0 && Math.random() < 0.05) {
        finalCode = 2;
      }
      return {
        type: TILE_CODE_TO_TYPE[finalCode as TileCode],
        elevation: finalCode === 4 ? 1 : 0,
      };
    })
  );
}
